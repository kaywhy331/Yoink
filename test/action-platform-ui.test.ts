import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import test from "node:test";

test("drop-window and watch-queue controls expose supersession, mode, countdown, and per-item readiness", () => {
  const root = process.cwd();
  const adminHtml = readFileSync(join(root, "apps", "web", "index.html"), "utf8");
  const adminScript = readFileSync(join(root, "apps", "web", "app.js"), "utf8");
  const userHtml = readFileSync(join(root, "apps", "web", "user.html"), "utf8");
  const userScript = readFileSync(join(root, "apps", "web", "user.js"), "utf8");

  assert.match(adminHtml, /<input name="supersedesId" id="dropWindowSupersedes" type="hidden">/);
  assert.doesNotMatch(adminHtml, /<select name="supersedesId"|Supersedes \(optional\)/);
  assert.doesNotMatch(adminScript, /renderDropWindowSupersedeOptions/);
  assert.match(adminScript, /form\.elements\.supersedesId\.value = window\.id/);
  assert.match(adminScript, /supersedesId: values\.supersedesId/);
  assert.match(adminScript, /\["scheduled", "active"\]\.includes\(window\.status\)/);
  assert.match(adminScript, /data-use-restock-pattern/);
  assert.match(adminScript, /function useRestockPatternForWindow/);
  assert.match(adminHtml, /id="dropWindowProductSearch"/);
  assert.match(adminHtml, /id="dropWindowProductSelection"/);
  assert.match(adminHtml, /id="restockPatternProductSearch"/);
  assert.match(adminHtml, /id="dropWindowDialog"/);
  assert.doesNotMatch(adminHtml, /Exact listing IDs/);
  assert.doesNotMatch(adminHtml, /name="spreadSeconds"/);
  assert.match(adminScript, /function searchListingPicker/);
  assert.match(adminScript, /Number\(values\.staggerMinutes\) \* 60/);
  assert.match(adminScript, /confidenceBps: Number\(values\.confidenceBps\)/);
  assert.match(adminScript, /\/admin\/drop-windows\/\$\{encodeURIComponent\(window\.id\)\}\/cancel/);
  assert.match(adminScript, /pattern\.sampleCount/);
  assert.match(adminScript, /pattern\.histogram/);
  assert.doesNotMatch(adminScript, /pattern\.localHourHistogram/);
  assert.match(adminScript, /qualificationNeedsAttention \? warning\.replaceAll/);

  assert.match(userHtml, /id="watchQueueMode"/);
  assert.match(userHtml, /Watch drops for active plans/);
  assert.doesNotMatch(userHtml, /read-only|\barmed\b/i);
  assert.match(userHtml, /data-settings-panel="purchase"[^>]*>[\s\S]*?Scheduled drop watching[\s\S]*?id="watchQueueMode"/);
  assert.match(userHtml, /id="callSelectionToolbar"[^>]*hidden/);
  assert.match(userHtml, /id="callBulkClear"/);
  assert.match(userScript, /\/api\/v1\/user\/watch-queue\/settings/);
  assert.match(userScript, /SET_WATCH_QUEUE_MODE/);
  assert.match(userScript, /function watchWindowSummary/);
  assert.match(userScript, /function watchReadinessSummary/);
  assert.match(userScript, /Watched automatically for your plan/);
  assert.doesNotMatch(userScript, /Observation remains read-only|Bounded read-only|Read-only checks/);
  assert.doesNotMatch(userHtml, /id="analyticsLatency"/);
  assert.doesNotMatch(userHtml, /id="sourceScorecards"/);
  assert.match(userScript, /Daily cap headroom/);
  assert.match(userScript, /Monthly cap headroom/);
  assert.doesNotMatch(userScript, /leaseToCartReadyMs|leaseToBaselineMs|baselineToOfferMs|offerToClickMs|settleToCartReadyMs/);
  assert.doesNotMatch(userScript, /function slowestChromePhase\(hops\)|Slowest phase:|actionLatencyMarkup/);
  assert.doesNotMatch(userScript, /latencyLabels\[key\] \|\| words\(key\)/);
  assert.match(userScript, /qualificationNeedsAttention \? labelFor\(STORE_CHECK_WARNING_LABELS, warning\)/);
  assert.match(userScript, /expiring: "Check again soon",\s+expired: "Sign in again",\s+version_changed: "Store changed, check again"/);
  const insightsRenderer = userScript.slice(userScript.indexOf("function renderActionPlatform()"), userScript.indexOf("function renderConnectors()"));
  assert.doesNotMatch(insightsRenderer, /p50|p95|\bms\b|sourceScorecards|analyticsLatency/);
  assert.match(adminHtml, /id="adminAnalyticsLatency"/);
  assert.match(adminScript, /Source observed → received/);
  assert.match(adminScript, /Chrome → cart ready/);
});
